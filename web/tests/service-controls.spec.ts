import { expect, test } from '@playwright/test';
import { mockConsole } from './fixtures';

for (const width of [390, 1440]) test(`sidebar shutdown confirms and preserves keyboard focus at ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const state = await mockConsole(page);
  await page.goto('/?view=groups');
  const sidebar = page.locator('aside.sidebar');
  if (width < 761) await page.getByRole('button', { name: '展开导航菜单', exact: true }).click();
  const trigger = sidebar.getByRole('button', { name: '停止中转站', exact: true });
  await expect(trigger).toBeVisible();
  await expect(trigger).toHaveText('');
  await expect(trigger).toHaveAttribute('title', '停止中转站');
  await sidebar.screenshot({ path: testInfo.outputPath('sidebar-service-control.png') });
  await trigger.click();
  const dialog = page.getByRole('dialog', { name: '停止整个中转站？', exact: true });
  const cancel = dialog.getByRole('button', { name: '继续运行', exact: true });
  const confirm = dialog.getByRole('button', { name: '确认停止', exact: true });
  await expect(dialog).toBeVisible();
  await expect(cancel).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(confirm).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(cancel).toBeFocused();
  await dialog.screenshot({ path: testInfo.outputPath('shutdown-confirmation.png') });
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  expect(state.writes.filter(item => item.path === '/service/stop')).toHaveLength(0);
  if (width < 761) await expect(sidebar).toHaveAttribute('aria-modal', 'true');
  await trigger.click();
  await cancel.click();
  await expect(trigger).toBeFocused();
  await trigger.click();
  await confirm.click();
  await expect(page.getByRole('heading', { name: '中转站正在停止', exact: true })).toBeVisible();
  expect(state.writes.filter(item => item.path === '/service/stop')).toHaveLength(1);
});
