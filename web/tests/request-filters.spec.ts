import { test, expect } from '@playwright/test';
import { mockConsole, nativeId, groupId } from './fixtures';

test('account keywords search historical names across pages and exact selection replaces them', async ({ page }) => {
  const state = await mockConsole(page);
  const record = state.records[0];
  for (let i = 0; i < 22; i++) state.records.push({ ...record, id: `historical-${i}`, accountId: '10000000-0000-0000-0000-000000000099', accountName: 'nn 历史账户' });
  await page.goto('/?view=requests&page=2');
  const pager = page.getByRole('navigation', { name: '请求记录分页' });
  await expect(pager).toContainText('第 2 / 2 页');
  await page.getByLabel('筛选字段', { exact: true }).selectOption('accountId');
  const input = page.getByLabel('账户筛选内容');
  await input.fill('nn');
  await input.press('Enter');
  await expect(pager).toContainText('第 1 / 2 页 · 共 22 条');
  expect(state.statisticsQueries.at(-1)?.get('accountName')).toBe('nn');
  expect(state.statisticsQueries.at(-1)?.has('accountId')).toBe(false);
  await pager.getByRole('button', { name: '下一页' }).click();
  await expect(page.locator('.records-table tbody tr')).toHaveCount(2);
  await page.reload();
  await expect(input).toHaveValue('nn');
  await input.fill('本机 Codex');
  await page.getByRole('button', { name: '搜索请求记录', exact: true }).click();
  await expect(pager).toContainText('第 1 / 1 页 · 共 1 条');
  expect(state.statisticsQueries.at(-1)?.get('accountId')).toBe(nativeId);
  expect(state.statisticsQueries.at(-1)?.has('accountName')).toBe(false);
  await input.fill('10000000-0000-0000-0000-000000000099');
  await input.press('Enter');
  await expect(pager).toContainText('第 1 / 2 页 · 共 22 条');
  expect(state.statisticsQueries.at(-1)?.get('accountId')).toBe('10000000-0000-0000-0000-000000000099');
  expect(state.statisticsQueries.at(-1)?.has('accountName')).toBe(false);
  await input.fill('不存在');
  await input.press('Enter');
  await expect(page.getByText('当前范围没有请求记录')).toBeVisible();
  await expect(page.getByText('暂时无法读取记录')).toHaveCount(0);
  await page.getByLabel('已应用筛选', { exact: true }).click();
  await page.getByRole('button', { name: '移除账户筛选' }).click();
  await expect(pager).toContainText('共 23 条');
  expect(state.statisticsQueries.at(-1)?.has('accountName')).toBe(false);
});

test('group keywords clear account filters and can switch to an exact group', async ({ page }) => {
  const state = await mockConsole(page);
  await page.goto('/?view=requests&accountName=missing');
  await expect(page.getByText('当前范围没有请求记录')).toBeVisible();
  await page.getByLabel('筛选字段', { exact: true }).selectOption('groupId');
  const input = page.getByLabel('分组筛选内容');
  await input.fill('默认');
  await input.press('Enter');
  await expect(page.locator('.records-table tbody tr')).toHaveCount(1);
  expect(state.statisticsQueries.at(-1)?.get('groupName')).toBe('默认');
  expect(state.statisticsQueries.at(-1)?.has('groupId')).toBe(false);
  expect(state.statisticsQueries.at(-1)?.has('accountName')).toBe(false);
  await input.fill('默认分组');
  await input.press('Enter');
  await expect.poll(() => state.statisticsQueries.at(-1)?.get('groupId')).toBe(groupId);
  expect(state.statisticsQueries.at(-1)?.has('groupName')).toBe(false);
  await input.fill('');
  await input.press('Enter');
  await expect(page.getByLabel('已应用筛选', { exact: true })).toHaveCount(0);
});

test('invalid status stays local with an accessible error and recovers after correction', async ({ page }) => {
  const state = await mockConsole(page);
  await page.goto('/?view=requests');
  await expect(page.locator('.records-table tbody tr')).toHaveCount(1);
  const queries = state.statisticsQueries.length;
  await page.getByLabel('筛选字段', { exact: true }).selectOption('status');
  const input = page.getByLabel('请求状态筛选内容');
  await input.fill('nn');
  await input.press('Enter');
  await expect(page.getByRole('alert')).toHaveText('请选择有效的请求状态。');
  await expect(input).toHaveAttribute('aria-invalid', 'true');
  expect(state.statisticsQueries).toHaveLength(queries);
  await expect(page.locator('.records-table tbody tr')).toHaveCount(1);
  await page.setViewportSize({ width: 375, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: '../.cache/request-filter-validation-mobile.png' });
  await input.fill('成功');
  await input.press('Enter');
  await expect.poll(() => state.statisticsQueries.at(-1)?.get('status')).toBe('succeeded');
  await expect(page.getByRole('alert')).toHaveCount(0);
});
